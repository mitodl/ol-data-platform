"""Raw-table fixtures for the local lake.

A unit whose inventory entry says ``strategies.local: fixture`` has no local
loader, so its raw tables have to be created from something committed. An
``ingest`` unit may carry one too: it is what the lake holds until the unit's
source is run against the local app (``ol-dbt ingest local``). This is
that something: one file per unit under ``ingestion/inventory/fixtures/``, named
as the unit file is, holding each table's columns with their types and a few
rows::

    schema_version: 1
    tables:
      raw__ocw__s3__course_content:
        columns:
          course_slug: string
          course_retrieved_at: timestamp
        rows:
        - course_slug: 18-01-fall-2020
          course_retrieved_at: 2026-01-01 00:00:00

The file carries the types because nothing else in the repository does: the dbt
source files name columns for some tables and types for almost none, and the
only other record is production Glue, which a contributor without AWS
credentials cannot read.

Rows are hand-written in the file or generated by the unit's factory package
(:mod:`ol_dbt_cli.fixture_factories`), never sampled. Raw application tables
hold learner data (``users_user``, ``auth_user``), and a sampling command would
put the scrubbing decision in code that runs against production. ``capture``
therefore takes the shape of a table and nothing else.

The loader writes through StarRocks, not pyiceberg: the local catalog hands
every client the in-cluster object store endpoint, which does not resolve from
the host, and StarRocks is the engine that then reads the tables.
"""

from __future__ import annotations

import datetime
import importlib
import json
import math
import re
import struct
from dataclasses import dataclass, field
from decimal import Context, Decimal
from pathlib import Path
from typing import TYPE_CHECKING, Any, Protocol, cast

import yaml

from ol_dbt_cli.lib.inventory import LOCAL_INGEST_STRATEGY

if TYPE_CHECKING:
    from collections.abc import Iterable, Mapping, MutableMapping

    from ol_dbt_cli.lib.inventory import Unit

FIXTURES_SUBDIR = "fixtures"
FACTORY_PACKAGE = "ol_dbt_cli.fixture_factories"
SCHEMA_VERSION = 1
FIXTURE_STRATEGY = "fixture"
# The local strategies a unit can have a fixture under. `omit` is the one left
# out: a fixture there would fill a unit the inventory says local does not hold.
FIXTURE_STRATEGIES = frozenset({FIXTURE_STRATEGY, LOCAL_INGEST_STRATEGY})

# Iceberg primitive names on the left, what StarRocks calls the column in a
# CREATE TABLE on an Iceberg catalog on the right. `timestamp` covers Iceberg's
# timestamptz as well: StarRocks reads both as DATETIME, and Glue reports both
# as `timestamp`, so a second name would record a difference nothing here can
# observe.
STARROCKS_TYPES: dict[str, str] = {
    "boolean": "BOOLEAN",
    "int": "INT",
    "long": "BIGINT",
    "float": "FLOAT",
    "double": "DOUBLE",
    "date": "DATE",
    "timestamp": "DATETIME",
    "string": "STRING",
}
_DECIMAL = re.compile(r"^decimal\((\d+),\s*(\d+)\)$")
_INTEGER_BITS = {"int": 32, "long": 64}
_FLOATING = frozenset({"float", "double"})
# What `full_refresh_append` and `incremental_append` end in, of a unit table's sync modes.
_APPEND_SUFFIX = "_append"

# Hive type names as Glue reports them for an Iceberg table.
_GLUE_TYPES: dict[str, str] = {
    "boolean": "boolean",
    "tinyint": "int",
    "smallint": "int",
    "int": "int",
    "integer": "int",
    "bigint": "long",
    "float": "float",
    "double": "double",
    "date": "date",
    "timestamp": "timestamp",
    "string": "string",
}
_GLUE_SIZED_STRING = re.compile(r"^(var)?char\(\d+\)$")


@dataclass
class TableFixture:
    """One raw table: its columns in order, and the rows to load."""

    raw_table: str
    columns: dict[str, str]
    rows: list[dict[str, Any]] = field(default_factory=list)


@dataclass
class UnitFixture:
    """One parsed fixture file."""

    path: Path
    tables: list[TableFixture]


class UnitFactories(Protocol):
    """What a unit's package under :mod:`ol_dbt_cli.fixture_factories` exposes."""

    SEED: int

    def generate(
        self, hand_written: Mapping[str, list[dict[str, Any]]], scale: float
    ) -> dict[str, list[dict[str, Any]]]:
        """Return the generated rows of each raw table, the hand-written ones left out.

        ``hand_written`` holds copies. A change to a value in one (a treebeard
        parent's ``numchild``) is what loads.
        """
        ...


def starrocks_type(fixture_type: str) -> str:
    """Return the StarRocks column type for a fixture type.

    :param fixture_type: A key of :data:`STARROCKS_TYPES`, or ``decimal(p,s)``.
    :returns: The type as StarRocks DDL spells it.
    :rtype: str
    :raises ValueError: For a type the fixture format does not have.
    """
    if fixture_type in STARROCKS_TYPES:
        return STARROCKS_TYPES[fixture_type]
    if match := _DECIMAL.match(fixture_type):
        return f"DECIMAL({match.group(1)}, {match.group(2)})"
    msg = f"unsupported fixture type {fixture_type!r}; use one of {', '.join(STARROCKS_TYPES)} or decimal(p,s)"
    raise ValueError(msg)


def fixture_type_from_glue(glue_type: str) -> str | None:
    """Return the fixture type for a Glue column type, or ``None`` if it has none.

    Nested types (``struct``, ``array``, ``map``) and ``binary`` have none: the
    loader passes rows as SQL parameters, which cannot carry them.
    """
    normalized = glue_type.strip().lower()
    if normalized in _GLUE_TYPES:
        return _GLUE_TYPES[normalized]
    if _GLUE_SIZED_STRING.match(normalized):
        return "string"
    if _DECIMAL.match(normalized):
        return normalized.replace(" ", "")
    return None


def fixture_path(inventory_dir: Path, unit: Unit) -> Path:
    """Return where the fixture for ``unit`` lives: named as the unit file is."""
    return inventory_dir / FIXTURES_SUBDIR / unit.path.name


def parse_fixture(path: Path, unit: Unit) -> UnitFixture:
    """Read a fixture file and check it against its unit.

    :param path: The fixture file.
    :param unit: The inventory unit of the same name.
    :returns: The parsed fixture.
    :rtype: UnitFixture
    :raises ValueError: If the unit's local strategy takes no fixture, a table is not the
        unit's, a type is not in the format, or a row sets a column the table
        does not have, holds a value its column cannot, or repeats the primary
        key of an earlier row.
    """
    data = yaml.safe_load(path.read_text())
    if data["schema_version"] != SCHEMA_VERSION:
        msg = f"{path}: schema_version {data['schema_version']!r}, expected {SCHEMA_VERSION}"
        raise ValueError(msg)
    local_strategy = unit.data["strategies"]["local"]
    if local_strategy not in FIXTURE_STRATEGIES:
        msg = f"{path}: unit {unit.key} has strategies.local: {local_strategy}, which takes no fixture"
        raise ValueError(msg)
    declared = {table["raw_table"]: table for table in unit.tables}

    tables = []
    for raw_table, body in data["tables"].items():
        if raw_table not in declared:
            msg = f"{path}: {raw_table} is not a table of unit {unit.key}"
            raise ValueError(msg)
        columns: dict[str, str] = body["columns"]
        check_columns(columns, f"{path}: {raw_table}")
        rows = body.get("rows") or []
        table = TableFixture(raw_table=raw_table, columns=dict(columns), rows=list(rows))
        key_paths = declared[raw_table].get("primary_key") or []
        key_columns = [path[0] for path in key_paths]
        # A key the fixture cannot hold (a nested path, a column it does not
        # declare) is `validate_generated`'s to report: only generating needs it.
        comparable = (
            bool(key_paths)
            and all(len(path) == 1 and path[0] in columns for path in key_paths)
            and not _keeps_versions(declared[raw_table])
        )
        seen: dict[tuple[Any, ...], int] = {}
        for number, row in enumerate(rows, start=1):
            label = f"{path}: {raw_table} row {number}"
            check_row(row, columns, label)
            # A row with no key is NULL there, as any column it leaves out is.
            if not comparable or any(row.get(column) is None for column in key_columns):
                continue
            key = stored_key(table, row, key_columns, label)
            if key in seen:
                value = ", ".join(f"{column}={row[column]!r}" for column in key_columns)
                msg = f"{label} repeats the primary key of row {seen[key]}, {value}"
                raise ValueError(msg)
            seen[key] = number
        tables.append(table)
    return UnitFixture(path=path, tables=tables)


def check_columns(columns: Mapping[str, str], label: str) -> None:
    """Check that a table declares columns, and only of types the format has.

    :param columns: ``{column: fixture type}``.
    :param label: Names the table in an error.
    :raises ValueError: If there are no columns or a type is not in the format.
    """
    if not columns:
        msg = f"{label} has no columns"
        raise ValueError(msg)
    for column, fixture_type in columns.items():
        try:
            starrocks_type(fixture_type)
        except ValueError as error:
            msg = f"{label}.{column}: {error}"
            raise ValueError(msg) from error


def check_row(row: Mapping[str, Any], columns: Mapping[str, str], label: str) -> None:
    """Check that a fixture row sets only the table's columns, each to a value its type can hold.

    :param row: A hand-written row.
    :param columns: The table's ``{column: fixture type}``.
    :param label: Names the row in an error.
    :raises ValueError: If the row sets a column the table does not have, or a
        value its column cannot hold.
    """
    if unknown := sorted(set(row) - set(columns)):
        msg = f"{label} sets {', '.join(unknown)}, which the table does not have"
        raise ValueError(msg)
    for column, value in row.items():
        if value is None:
            continue
        try:
            _stored_value(value, columns[column])
        except (ValueError, TypeError, ArithmeticError, struct.error) as error:
            msg = f"{label} has {value!r} in column {column}, which is not a valid {columns[column]}"
            raise ValueError(msg) from error


def load_fixtures(inventory_dir: Path, units: Iterable[Unit], *, selected: bool = False) -> list[UnitFixture]:
    """Read the committed fixtures of ``units``.

    :param inventory_dir: Directory holding ``units/`` and ``fixtures/``.
    :param units: The inventory units to read fixtures for.
    :param selected: The units were named by the caller, so one with no fixture
        file is an error, not a unit nobody has written a fixture for yet.
    :raises ValueError: If a fixture is invalid, a selected unit has none, or a
        fixture file has no unit of the same name.
    """
    units = list(units)
    paths = {fixture_path(inventory_dir, unit): unit for unit in units}
    if selected:
        if missing := [str(path) for path in paths if not path.exists()]:
            msg = f"no fixture file: {', '.join(missing)}"
            raise ValueError(msg)
    else:
        committed = set((inventory_dir / FIXTURES_SUBDIR).glob("*.yml"))
        if orphans := sorted(str(path) for path in committed - set(paths)):
            msg = f"fixture with no inventory unit of the same name: {', '.join(orphans)}"
            raise ValueError(msg)
    return [parse_fixture(path, unit) for path, unit in sorted(paths.items()) if path.exists()]


def unit_factories(unit: Unit, package: str = FACTORY_PACKAGE) -> UnitFactories | None:
    """Return the factory package of ``unit``, or ``None`` if it has none.

    :param unit: The inventory unit.
    :param package: The package holding one subpackage per unit, named as the
        unit file is.
    :returns: The imported package, which generates rows for the unit's fixture.
    :rtype: UnitFactories | None
    :raises ValueError: If the package lacks ``SEED`` or ``generate``.
    """
    name = f"{package}.{unit.path.stem}"
    try:
        module = importlib.import_module(name)
    except ModuleNotFoundError as error:
        # Only the unit's own package may be absent. Anything else that fails
        # to import (factory_boy, a sibling module) is a broken package.
        if error.name != name:
            raise
        return None
    # A directory holding only `_generated.py`, or a `__pycache__` left by
    # another branch, imports as an empty namespace package.
    if lacking := [attribute for attribute in ("SEED", "generate") if not hasattr(module, attribute)]:
        msg = (
            f"{name} has no {' or '.join(lacking)}; a unit's factory package defines both in its __init__.py. "
            f"A directory another branch left holding only __pycache__ imports like this: delete "
            f"{', '.join(module.__path__)}, or load with --no-generate"
        )
        raise ValueError(msg)
    return cast("UnitFactories", module)


def validate_generated(fixture: UnitFixture, unit: Unit, generated: Mapping[str, list[dict[str, Any]]]) -> None:
    """Check the rows a unit's factories generated against its fixture and the inventory.

    A column a generated row leaves out is NULL, as in a hand-written row.
    Foreign keys are declared in neither file, so references are not checked.

    :param fixture: The unit's parsed fixture file.
    :param unit: The inventory unit, for each table's ``primary_key``.
    :param generated: What the unit's ``generate`` returned.
    :raises ValueError: If a table is not in the fixture file, a row sets a
        column the table does not have, a primary key column is NULL or holds
        a value its type cannot, or a primary key repeats one of the
        hand-written or generated rows of a table that does not keep every
        version of a row.
    """
    tables = {table.raw_table: table for table in fixture.tables}
    primary_keys = {table["raw_table"]: table["primary_key"] for table in unit.tables if table.get("primary_key")}
    versioned = {table["raw_table"] for table in unit.tables if _keeps_versions(table)}
    for raw_table, rows in generated.items():
        where = f"{unit.key} factories: {raw_table}"
        if raw_table not in tables:
            msg = f"{where} is not a table of {fixture.path}"
            raise ValueError(msg)
        table = tables[raw_table]
        key_paths = primary_keys.get(raw_table, [])
        if nested := [".".join(path) for path in key_paths if len(path) > 1]:
            msg = f"{where} has nested primary key path {', '.join(nested)}, which a fixture row cannot hold"
            raise ValueError(msg)
        key_columns = [path[0] for path in key_paths]
        if undeclared := [column for column in key_columns if column not in table.columns]:
            msg = f"{where} has primary key column {', '.join(undeclared)}, which {fixture.path} does not declare"
            raise ValueError(msg)
        seen = {
            stored_key(table, row, key_columns, f"{where} hand-written row {number}")
            for number, row in enumerate(table.rows, start=1)
        }
        for number, row in enumerate(rows, start=1):
            if unknown := sorted(set(row) - set(table.columns)):
                msg = f"{where} generated row {number} sets {', '.join(unknown)}, which the table does not have"
                raise ValueError(msg)
            if not key_columns:
                continue
            if missing := [column for column in key_columns if row.get(column) is None]:
                msg = f"{where} generated row {number} has no value for primary key column {', '.join(missing)}"
                raise ValueError(msg)
            key = stored_key(table, row, key_columns, f"{where} generated row {number}")
            if key in seen and raw_table not in versioned:
                value = ", ".join(f"{column}={row[column]!r}" for column in key_columns)
                msg = f"{where} generated row {number} repeats primary key {value}"
                raise ValueError(msg)
            seen.add(key)


def _keeps_versions(table: Mapping[str, Any]) -> bool:
    """Return whether an inventory table keeps every version of a row, so its primary key repeats.

    Staging deduplicates an append table, so a key its raw rows repeat is not an error.
    """
    return table["sync_mode"].endswith(_APPEND_SUFFIX)


def stored_key(table: TableFixture, row: Mapping[str, Any], key_columns: list[str], label: str) -> tuple[Any, ...]:
    """Return the key of ``row`` as the table will hold it, so `"1"` and `1` in a ``long`` column are one key.

    :param table: The table ``row`` belongs to.
    :param row: A hand-written or generated row.
    :param key_columns: The table's primary key columns.
    :param label: Names the row in an error.
    :returns: Each key column's value as stored, ``None`` where the row has none.
    :rtype: tuple[Any, ...]
    :raises ValueError: If a key column holds a value its type cannot.
    """
    key = []
    for column in key_columns:
        value, fixture_type = row.get(column), table.columns[column]
        try:
            key.append(None if value is None else _stored_value(value, fixture_type))
        except (ValueError, TypeError, ArithmeticError, struct.error) as error:
            msg = f"{label} has {value!r} in primary key column {column}, which is not a valid {fixture_type}"
            raise ValueError(msg) from error
    return tuple(key)


def _stored_value(value: Any, fixture_type: str) -> Any:  # noqa: C901, PLR0911
    # int() and float() take a bool (YAML `true`) as 1, which a numeric column
    # would then hold. bool is an int, so it is named before the int branch.
    if isinstance(value, bool) and (
        fixture_type in _INTEGER_BITS or fixture_type in _FLOATING or _DECIMAL.match(fixture_type)
    ):
        raise TypeError(value)
    if fixture_type in _INTEGER_BITS:
        number = int(value)
        # int() drops the fraction of a float or Decimal. Of a string it raises.
        if not isinstance(value, str) and number != value:
            raise ValueError(value)
        limit = 2 ** (_INTEGER_BITS[fixture_type] - 1)
        if not -limit <= number < limit:
            raise OverflowError(number)
        return number
    if fixture_type == "float":
        # Through single precision, so two doubles that share a FLOAT are one key.
        single = struct.unpack("f", struct.pack("f", float(value)))[0]
        if math.isinf(single) and not math.isinf(float(value)):
            raise OverflowError(value)
        return single
    if fixture_type == "double":
        return float(value)
    if match := _DECIMAL.match(fixture_type):
        precision, scale = int(match.group(1)), int(match.group(2))
        exact = Decimal(str(value))
        if not exact.is_finite():
            raise ValueError(exact)
        # In integers, because Decimal arithmetic rounds to the context's 28
        # digits and a decimal(38,9) has more. A value with more digits than
        # the column has is rejected, not rounded as the engine might round it.
        _, digits, exponent = exact.as_tuple()
        unscaled, shift = int("".join(map(str, digits))), int(exponent) + scale
        dropped = 0
        if shift >= 0:
            unscaled *= 10**shift
        else:
            unscaled, dropped = divmod(unscaled, 10**-shift)
        if dropped or unscaled >= 10**precision:
            raise OverflowError(exact)
        return exact
    if fixture_type == "boolean":
        if value not in (0, 1):
            raise ValueError(value)
        return bool(value)
    if fixture_type == "string":
        # str() of these is their repr (`b'x'`, a YAML `!!binary` or `!!set`), not text.
        if isinstance(value, (set, frozenset, tuple, bytes, bytearray)):
            raise TypeError(value)
        return str(value)
    if fixture_type == "date":
        day = datetime.date.fromisoformat(value) if isinstance(value, str) else value
        if not isinstance(day, datetime.date):
            raise TypeError(day)
        return day.date() if isinstance(day, datetime.datetime) else day
    if fixture_type == "timestamp":
        moment = datetime.datetime.fromisoformat(value) if isinstance(value, str) else value
        if not isinstance(moment, datetime.datetime):
            moment = datetime.datetime.combine(moment, datetime.time())
        # The connector writes an aware datetime's wall clock and drops its offset.
        return moment.replace(tzinfo=None)
    return value


def coerce_value(value: Any, fixture_type: str) -> Any:
    """Return a generated ``value`` as a column of ``fixture_type`` holds it.

    A hand-written value is what YAML made of it. A generated one is whatever
    its provider returned, so it is brought to the column's type here: a
    ``decimal(p,s)`` is rounded to ``s`` places, an aware ``timestamp`` is moved
    to UTC and loses its offset, and a scalar in a ``string`` column becomes
    its ``str``. A mapping or a list there is left for the loader to write
    as JSON. Anything else goes through the check a hand-written value does.

    :param value: The generated value, not ``None``.
    :param fixture_type: The column's type in the fixture file.
    :returns: The value to insert.
    :raises ValueError: If the column cannot hold the value. Also
        ``TypeError``, ``ArithmeticError`` or ``struct.error``, depending on
        the type.
    """
    if fixture_type == "string":
        if isinstance(value, (dict, list)):
            # Raises TypeError here, where the column is known, not in the loader.
            json.dumps(value)
            return value
    elif match := _DECIMAL.match(fixture_type):
        precision, scale = int(match.group(1)), int(match.group(2))
        # Raises InvalidOperation when the rounded value has more than `precision` digits.
        value = Decimal(str(value)).quantize(Decimal(1).scaleb(-scale), context=Context(prec=precision))
    elif fixture_type == "timestamp":
        if isinstance(value, str):
            value = datetime.datetime.fromisoformat(value)
        if isinstance(value, datetime.datetime) and value.tzinfo is not None:
            value = value.astimezone(datetime.UTC)
    return _stored_value(value, fixture_type)


def _quote(identifier: str) -> str:
    return "`" + identifier.replace("`", "``") + "`"


def qualified_name(catalog: str, schema: str, table: str | None = None) -> str:
    """Return a backtick-quoted ``catalog.schema[.table]``."""
    parts = [catalog, schema] if table is None else [catalog, schema, table]
    return ".".join(_quote(part) for part in parts)


def create_table_sql(table: TableFixture, catalog: str, schema: str) -> str:
    """Return the CREATE TABLE for ``table`` in an Iceberg catalog."""
    columns = ", ".join(f"{_quote(name)} {starrocks_type(kind)}" for name, kind in table.columns.items())
    return f"CREATE TABLE {qualified_name(catalog, schema, table.raw_table)} ({columns})"


def insert_sql(table: TableFixture, catalog: str, schema: str) -> str:
    """Return a parameterized INSERT covering every column of ``table``."""
    columns = ", ".join(_quote(name) for name in table.columns)
    placeholders = ", ".join(["%s"] * len(table.columns))
    return f"INSERT INTO {qualified_name(catalog, schema, table.raw_table)} ({columns}) VALUES ({placeholders})"  # noqa: S608


def row_parameters(table: TableFixture) -> list[tuple[Any, ...]]:
    """Return each row as INSERT parameters, in column order.

    A column the row leaves out is NULL. A mapping or list is written as JSON
    text, so a JSON-in-a-string column (``data_json``, an Airbyte ``metadata``)
    can be written in the fixture as the structure it holds.
    """
    return [tuple(_parameter(row.get(column)) for column in table.columns) for row in table.rows]


def _parameter(value: Any) -> Any:
    if isinstance(value, (dict, list)):
        return json.dumps(value)
    return value


def merge_captured(existing: MutableMapping[str, Any] | None, captured: Mapping[str, Mapping[str, str]]) -> Any:
    """Fold freshly captured column maps into a fixture document.

    A table already in the document keeps its rows and takes the captured
    columns; a table not captured is left alone. ``existing`` is changed in
    place and returned, so a round-trip YAML document keeps its comments.

    :param existing: The parsed fixture file, or ``None`` when there is none.
    :param captured: ``{raw_table: {column: fixture type}}``.
    :returns: The document to write.
    """
    document: MutableMapping[str, Any] = (
        existing if existing is not None else {"schema_version": SCHEMA_VERSION, "tables": {}}
    )
    tables: MutableMapping[str, Any] = document["tables"]
    for raw_table, columns in captured.items():
        if raw_table in tables:
            tables[raw_table]["columns"] = dict(columns)
        else:
            tables[raw_table] = {"columns": dict(columns), "rows": []}
    return document
